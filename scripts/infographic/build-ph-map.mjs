/**
 * Builds the Philippines outline drawn on the accomplishment infographic
 * (features/accomplishment/infographic/ph-map.ts) from Natural Earth 1:10m country borders (public domain).
 *
 *   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0
 *   node scripts/infographic/build-ph-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-10m.json"), "utf8"));
const geom = feature(topo, topo.objects.countries).features.find((f) => f.properties.name === "Philippines").geometry;

// Equirectangular, longitudes shortened by cos(12°) so the islands keep their shape.
const BOX = { west: 116.8, east: 126.8, south: 4.4, north: 21.3 };
const WIDTH = 420;
const K = Math.cos((12 * Math.PI) / 180);
const scale = WIDTH / ((BOX.east - BOX.west) * K);
const HEIGHT = Math.round((BOX.north - BOX.south) * scale);
const project = ([lng, lat]) => [(lng - BOX.west) * K * scale, (BOX.north - lat) * scale];

/** Douglas–Peucker on projected points. */
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const d = Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
      if (d > worst) {
        worst = d;
        at = i;
      }
    }
    if (worst > tolerance) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => { const [nx, ny] = pts[(i + 1) % pts.length]; return s + x * ny - nx * y; }, 0) / 2);
const f1 = (n) => (Math.round(n * 10) / 10).toString();

const parts = [];
for (const polygon of geom.coordinates) {
  const ring = polygon[0].map(project);
  if (area(ring) < 2) continue; // islets under ~2 px² vanish at this size
  // A closed ring starts and ends on the same point: simplify its two halves, split at the farthest point.
  const [sx, sy] = ring[0];
  let far = 1;
  ring.forEach(([x, y], i) => {
    if (Math.hypot(x - sx, y - sy) > Math.hypot(ring[far][0] - sx, ring[far][1] - sy)) far = i;
  });
  const pts = [...simplify(ring.slice(0, far + 1), 0.45), ...simplify(ring.slice(far), 0.45).slice(1)];
  if (pts.length < 4) continue;
  parts.push(`M${pts.map(([x, y]) => `${f1(x)} ${f1(y)}`).join("L")}Z`);
}
const path = parts.join("");

const out = `/* Generated by scripts/infographic/build-ph-map.mjs from Natural Earth 1:10m (public domain). Do not edit. */

/** The map's size in SVG units. */
export const PH_MAP = { width: ${WIDTH}, height: ${HEIGHT} } as const;

const BOX = ${JSON.stringify(BOX)};
const K = ${K};
const SCALE = ${scale};

/** A longitude / latitude in map units. */
export function projectPh(lng: number, lat: number): [number, number] {
  return [(lng - BOX.west) * K * SCALE, (BOX.north - lat) * SCALE];
}

/** The Philippine islands as one SVG path. */
export const PH_PATH =
  "${path}";
`;
writeFileSync(new URL("../../features/accomplishment/infographic/ph-map.ts", import.meta.url), out);
console.log(`ph-map.ts: ${WIDTH}×${HEIGHT}, ${parts.length} islands, ${(path.length / 1024).toFixed(1)} KB`);
